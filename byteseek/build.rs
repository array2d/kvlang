// 链接 stock 三方 .so（camelCase，符合 deepx-design/doc/abi-naming-standard.md）：
//   kvlang_runtime  —— 模式2 主导执行 + rwirext 宿主 ABI（repo lib/）
//   kvspace         —— dispatch 前端，按 DSN 运行时选后端（repo lib/，后端 lib/kvspace/）
//   kvlanglayout    —— .kv 编译入库（kvlang·* rwir + 启动 layout stdlib 用，repo lib/）
// 并把 stdlib/**/*.kv（顶层语言级标准库）全部 include_str! 进二进制（EMBEDDED_KV），启动时 layout 进 kvspace。
use std::path::{Path, PathBuf};

fn collect_kv(dir: &Path, files: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for e in entries.flatten() {
        let p = e.path();
        if p.is_dir() {
            collect_kv(&p, files);
        } else if p.extension().is_some_and(|x| x == "kv") {
            files.push(p);
        }
    }
}

/// #493 embed：把发布版 .so/.dylib 的字节嵌进可执行文件（include_bytes!），不直接链接。
fn emit_embed(manifest: &str) {
    // payload 目录固定为 build/embed（由 tools/stage_embed.sh 组装）；
    // 不读任何构建环境变量。产物后缀：Linux=.so(+版本号) macOS=.dylib。
    let dir = format!("{manifest}/../build/embed");
    let (ks_ext, rt_ext) = if cfg!(target_os = "macos") {
        (".dylib", ".dylib")
    } else {
        (".so.1", ".so")
    };
    let names = [
        ("EMBED_KVSPACE", &format!("libkvspace{ks_ext}")),
        // 默认 c2 runtime；C 版（libkvlang_runtime.so）仅作 A/B fallback。
        ("EMBED_KVLANG_RUNTIME", &format!("libkvlang_runtimec2{rt_ext}")),
        ("EMBED_KVLANGLAYOUT", &format!("libkvlanglayout{rt_ext}")),
        ("EMBED_KVSPACE_C", &format!("libkvspace-c{ks_ext}")),
        ("EMBED_KVSPACE_DURABLE", &format!("libkvspace_durable{ks_ext}")),
    ];
    for (var, file) in names {
        let mut found = None;
        for sub in ["", "kvspace/"] {
            let p = format!("{dir}/{sub}{file}");
            if std::path::Path::new(&p).is_file() {
                found = Some(p);
                break;
            }
        }
        let p = found.unwrap_or_else(|| {
            panic!("embed: {file} not found under {dir} (run tools/stage_embed.sh first)")
        });
        println!("cargo:rustc-env={var}={p}");
        println!("cargo:rerun-if-changed={p}");
    }
    gen_shim(&format!("{manifest}/src/ffi.rs"));
}

/// 从 ffi.rs 的唯一 extern 块生成 shim：每符号一个函数指针 + 同签名转发 + bind()。
fn gen_shim(ffi_rs: &str) {
    let src = std::fs::read_to_string(ffi_rs).expect("read ffi.rs");
    let open = "unsafe extern \"C\" {";
    let start = src.find(open).expect("extern block") + open.len();
    let end = start + src[start..].find("\n}\n").expect("extern block end");
    let body: String = src[start..end]
        .lines()
        .filter(|l| !l.trim_start().starts_with("//"))
        .collect::<Vec<_>>()
        .join("\n");

    let mut out = String::from("// generated by build.rs (feature = embed)\n");
    let mut sigs: Vec<(String, Vec<String>, String)> = Vec::new();
    for part in body.split(';') {
        let p = part.trim();
        if p.is_empty() {
            continue;
        }
        let (head, ret) = match p.rsplit_once("->") {
            Some((a, b)) => (a.trim(), b.trim().to_string()),
            None => (p, "()".to_string()),
        };
        let op = head.find('(').expect("fn args");
        let name = head[..op]
            .trim()
            .split_whitespace()
            .last()
            .unwrap()
            .to_string();
        let cl = head.rfind(')').expect("fn args end");
        let mut args = Vec::new();
        for a in head[op + 1..cl].split(',') {
            let a = a.trim();
            if a.is_empty() {
                continue;
            }
            args.push(a.split_once(':').expect("arg type").1.trim().to_string());
        }
        sigs.push((name, args, ret));
    }
    for (name, args, ret) in &sigs {
        let params: Vec<String> = args
            .iter()
            .enumerate()
            .map(|(i, t)| format!("_a{i}: {t}"))
            .collect();
        let tys = args.join(", ");
        let calls: Vec<String> = (0..args.len()).map(|i| format!("_a{i}")).collect();
        out.push_str(&format!(
            "#[allow(non_upper_case_globals)]\nstatic mut P_{name}: *mut c_void = std::ptr::null_mut();\n"
        ));
        out.push_str(&format!(
            "pub unsafe fn {name}({params}) -> {ret} {{\n    type F = unsafe extern \"C\" fn({tys}) -> {ret};\n    std::mem::transmute::<*mut c_void, F>(P_{name})({calls})\n}}\n",
            params = params.join(", "),
            calls = calls.join(", ")
        ));
    }
    out.push_str("pub fn bind(libs: &[(&str, *mut c_void)]) {\n    unsafe {\n");
    for (name, _, _) in &sigs {
        out.push_str(&format!(
            "        P_{name} = find(libs, \"{name}\")\n            .unwrap_or_else(|| die(\"missing symbol {name}\"));\n"
        ));
    }
    out.push_str(
        "    }\n}\n\nfn find(libs: &[(&str, *mut c_void)], name: &str) -> Option<*mut c_void> {\n",
    );
    out.push_str("    let c = std::ffi::CString::new(name).unwrap();\n    for (_, h) in libs {\n        let p = unsafe { libc::dlsym(*h, c.as_ptr()) };\n        if !p.is_null() {\n            return Some(p);\n        }\n    }\n    None\n}\n\nfn die(msg: &str) -> ! {\n    eprintln!(\"kvlang-single: {msg}\");\n    std::process::abort()\n}\n");
    let out_dir = std::env::var("OUT_DIR").unwrap();
    std::fs::write(format!("{out_dir}/embed_shim.rs"), out).unwrap();
    println!("cargo:rerun-if-changed={ffi_rs}");
}

fn main() {
    let manifest = env!("CARGO_MANIFEST_DIR");
    // 两级布局（repo 即 prefix）：库在 lib/，后端在 lib/kvspace/，不装 /usr。
    let lib = format!("{manifest}/../lib");
    let backend = format!("{lib}/kvspace");

    if std::env::var("CARGO_FEATURE_EMBED").is_ok() {
        // #493：全部自有 .so 以字节嵌入，启动时 memfd + dlopen 从内存加载。
        emit_embed(manifest);
    } else {
        println!("cargo:rustc-link-search=native={lib}");
        println!("cargo:rustc-link-search=native={backend}");
        println!("cargo:rustc-link-lib=dylib=kvlang_runtimec2");
        println!("cargo:rustc-link-lib=dylib=kvspace");
        println!("cargo:rustc-link-lib=dylib=kvlanglayout");

        if cfg!(target_os = "macos") {
            // macOS：ld64 无 --disable-new-dtags；$ORIGIN 对应 @loader_path
            println!("cargo:rustc-link-arg=-Wl,-rpath,@loader_path/../lib");
            println!("cargo:rustc-link-arg=-Wl,-rpath,@loader_path/../lib/kvspace");
        } else {
            println!("cargo:rustc-link-arg=-Wl,--disable-new-dtags"); // rpath 转 DT_RPATH，传递解析子依赖
            println!("cargo:rustc-link-arg=-Wl,-rpath,$ORIGIN/../lib");
            println!("cargo:rustc-link-arg=-Wl,-rpath,$ORIGIN/../lib/kvspace");
        }
    }

    // 内嵌顶层 stdlib/**/*.kv → EMBEDDED_KV。
    let libdir = format!("{manifest}/../stdlib");
    let mut files: Vec<PathBuf> = Vec::new();
    collect_kv(Path::new(&libdir), &mut files);
    files.sort();
    let mut code = String::from("pub static EMBEDDED_KV: &[(&str, &str)] = &[\n");
    for p in &files {
        let rel = p.strip_prefix(&libdir).unwrap_or(p);
        let name = rel.to_string_lossy().trim_start_matches('/').to_string();
        let abs = p.to_string_lossy();
        code.push_str(&format!("    ({name:?}, include_str!({abs:?})),\n"));
        println!("cargo:rerun-if-changed={abs}");
    }
    code.push_str("];\n");
    let out = std::env::var("OUT_DIR").unwrap();
    std::fs::write(format!("{out}/embedded_kv.rs"), code).unwrap();
    println!("cargo:rerun-if-changed={libdir}");
}
