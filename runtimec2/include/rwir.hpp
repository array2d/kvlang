struct Entry {
    const char* name;
    Op op;
    Kind kind;
    std::uint8_t width;
    Class cls;
    Impl impl;
    RwirHandlerId handler;
};

// = C runtime 的 myrwircaps（能力表，opcode→处理器）。
extern const Entry myrwircaps[];
extern const int kMyrwircapsN;

// 名字 → 表项；未命中返回 nullptr（非本 runtime 的 rwir）。
const Entry* find_myrwircap(const char* name, std::uint32_t len) noexcept;

// rwir id → 表内名字；越界返回 "<unknown>"（只用于诊断文本）。
inline const char* rwir_name(std::uint16_t id) noexcept {
    return id < static_cast<std::uint16_t>(kMyrwircapsN) ? myrwircaps[id].name
                                                         : "<unknown>";
}

